function normalize(text: string | null | undefined): string {
  return (text ?? "").toLowerCase().replace(/\s+/g, "");
}

// 由多段文字（場名、標題、原文）推理 18 區。命中即回傳，否則回 null。
export function inferDistrict(...texts: Array<string | null | undefined>): HkDistrict | null {
  const haystack = texts.map(normalize).join("");
  if (!haystack) return null;

  // 1) 已經係標準區名（例如 LLM 直接填咗「屯門區」）。
  for (const district of HK_DISTRICTS) {
    if (haystack.includes(normalize(district))) return district;
  }

  // 2) 直接地標／商場關鍵字。
  for (const [keyword, district] of Object.entries(LANDMARK_TO_DISTRICT)) {
    if (haystack.includes(normalize(keyword))) return district;
  }

  // 3) 口語區名（「屯門」「旺角」等，唔帶「區」字）。
  for (const [alias, district] of Object.entries(ALIAS_TO_DISTRICT)) {
    if (haystack.includes(normalize(alias))) return district;
  }

  return null;
}

// 將任意地區字串正規化做標準 18 區名；對唔到就回 null。
export function normalizeDistrict(value: string | null | undefined): HkDistrict | null {
  if (!value) return null;
  const trimmed = value.trim();
  if (isHkDistrict(trimmed)) return trimmed;
  return inferDistrict(trimmed);
}
